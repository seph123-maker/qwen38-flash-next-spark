#!/usr/bin/env python3
# qwen38-flash-v2 — rebuild the vLLM container from docker inspect VERBATIM,
# changing ONLY the Phase A/B values approved in the 2026-10-15 Argon audit
# (workspace/argon-audit-2026-10-15/VERDICT.md). Modes: diff (default, read-only), apply, rollback.
import json, re, subprocess, sys, time, urllib.request

NAME, ROLLBACK = "qwen38-flash", "qwen38-flash-ROLLBACK-1015"
ENV_SET = {"VLLM_PLE_MMAP_WORKERS": "16", "VLLM_PLE_MMAP_FAST_ROWS": "512"}   # VLLM_QSA_DET_LIB & draft-vocab paths carried verbatim
CMD_VALUE_SET = {"--max-model-len": "524288", "--max-num-seqs": "4", "--kv-cache-dtype": "fp8_e4m3"}
CMD_REGEX_SET = {  # (arg-name, pattern, replacement) — must hit exactly once or we abort
    "--hf-overrides":   (r'"factor":\s*4\.0', '"factor": 2.0'),
    "--speculative-config": (r'"max_model_len":\s*500000', '"max_model_len": 524288'),
}

def sh(*a, check=True):
    r = subprocess.run(a, capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.exit(f"FAIL: {' '.join(a)}\n{r.stderr.strip()}")
    return r.stdout

def derive():
    d = json.loads(sh("docker", "inspect", NAME))[0]
    cfg, hc = d["Config"], d["HostConfig"]
    cmd, env = list(cfg["Cmd"]), list(cfg["Env"])
    for i, a in enumerate(cmd):
        if a in CMD_VALUE_SET and i + 1 < len(cmd):
            cmd[i + 1] = CMD_VALUE_SET[a]
        for k, (pat, rep) in CMD_REGEX_SET.items():
            if a == k and i + 1 < len(cmd):
                new, n = re.subn(pat, rep, cmd[i + 1])
                if n != 1:
                    sys.exit(f"ABORT: {k} pattern {pat!r} matched {n}x — live config drifted from audit assumptions")
                cmd[i + 1] = new
    env = [f"{e.split('=',1)[0]}={ENV_SET[e.split('=',1)[0]]}" if e.split('=',1)[0] in ENV_SET else e for e in env]
    for k, v in ENV_SET.items():
        if not any(e.startswith(k + "=") for e in env):
            env.append(f"{k}={v}")
    for pat in (r'"factor":\s*2\.0', r'"max_model_len":\s*524288'):
        if not re.search(pat, " ".join(cmd)):
            sys.exit(f"ABORT: intended change {pat!r} not present in derived cmd")
    args = ["docker", "run", "--detach", "--name", NAME]
    rp = hc.get("RestartPolicy") or {}
    if rp.get("Name"): args += ["--restart", rp["Name"] + (f":{rp['MaximumRetryCount']}" if rp["Name"] == "on-failure" else "")]
    if hc.get("Runtime") and hc["Runtime"] not in ("", "runc"): args += ["--runtime", hc["Runtime"]]
    if hc.get("NetworkMode"): args += ["--network", hc["NetworkMode"]]
    if hc.get("IpcMode") and hc["IpcMode"] not in ("private", "shareable", ""): args += ["--ipc", hc["IpcMode"]]
    if hc.get("ShmSize"): args += ["--shm-size", str(hc["ShmSize"])]
    if hc.get("PidMode"): args += ["--pid", hc["PidMode"]]
    for h, pl in (hc.get("PortBindings") or {}).items():
        for b in pl: args += ["-p", f"{b.get('HostIp') or ''}:{b['HostPort']}:{h}".lstrip(":").replace("::", ":")] if b.get("HostIp") else ["-p", f"{b['HostPort']}:{h}"]
    for m in d["Mounts"]:
        if m["Type"] == "bind":
            args += ["-v", f"{m['Source']}:{m['Destination']}" + (":ro" if not m.get("RW", True) else "")]
    for dev in hc.get("DeviceRequests") or []:
        args += ["--gpus", "all"]
        break
    for ul in hc.get("Ulimits") or []: args += ["--ulimit", f"{ul['Name']}={ul['Soft']}:{ul['Hard']}"]
    for c in hc.get("CapAdd") or []: args += ["--cap-add", c]
    for c in hc.get("CapDrop") or []: args += ["--cap-drop", c]
    for s in hc.get("SecurityOpt") or []: args += ["--security-opt", s]
    if hc.get("Devices"):
        for dv in hc["Devices"]: args += ["--device", f"{dv['PathOnHost']}:{dv['PathInContainer']}:{dv.get('CgroupPermissions','rwm')}"]
    for e in env:
        k = e.split("=", 1)[0]
        if k in ("PATH", "HOME", "HOSTNAME"):
            continue  # regenerated by docker/shell; identical values otherwise
        args += ["-e", e]  # everything else VERBATIM (fleet rule: never filter vs image defaults)
    if cfg.get("Entrypoint"): args += ["--entrypoint", cfg["Entrypoint"][0]]
    args.append(cfg["Image"])
    if cfg.get("Entrypoint"): args += cmd
    ignored = sorted(k for k in hc if str(hc[k]) not in ("", "[]", "{}", "0", "None", "false", "[[8,1024]]")
                      and k not in ("RestartPolicy","NetworkMode","ShmSize","PortBindings","Binds","Mounts","DeviceRequests","Ulimits","CapAdd","CapDrop","SecurityOpt","Devices","IpcMode","PidMode"))
    return cmd, env, args, ignored

def running(name):
    try: return json.loads(sh("docker", "inspect", "--format", "{{.State.Running}}", name))[0:1] == "t" if False else sh("docker","inspect","--format","{{.State.Running}}",name).strip() == "true"
    except SystemExit: return False

mode = sys.argv[1] if len(sys.argv) > 1 else "diff"
cmd, env, args, ignored = derive()

if mode == "diff":
    d = json.loads(sh("docker", "inspect", NAME))[0]
    print("=== CHANGES (cmd) ===")
    for a, b in zip(d["Config"]["Cmd"], cmd):
        if a != b: print("  -", a, "\n  +", b)
    print("=== CHANGES (env) ===")
    for a, b in zip(sorted(d["Config"]["Env"]), sorted(env)):
        if a != b: print("  -", a, "\n  +", b)
    print("=== full docker-run will be:\n", " ".join(args[:60]))
    if ignored: print("NOTE: HostConfig keys non-default but NOT re-specified (image-defaults suspected):", ignored)
    sys.exit(0)

if mode == "rollback":
    if running(NAME): sh("docker", "stop", NAME)
    sh("docker", "rename", NAME, "qwen38-flash-FAILED-1015", check=False)
    sh("docker", "rename", ROLLBACK, NAME)
    sh("docker", "start", NAME)
    print("rolled back to pre-v2 container"); sys.exit(0)

# apply
if running(ROLLBACK): sys.exit("ABORT: rollback container already exists — resolve manually")
sh("docker", "rename", NAME, ROLLBACK)
sh("docker", "stop", ROLLBACK)
t0 = time.time()
subprocess.run(args, check=True)
print("new container starting; warming up…")
while time.time() - t0 < 360:
    try:
        urllib.request.urlopen("http://127.0.0.1:8000/health", timeout=3); print(f"HEALTHY after {time.time()-t0:.0f}s"); break
    except Exception: time.sleep(5)
else:
    sys.exit("TIMEOUT: not healthy in 360s — run: python3 /root/qwen38-flash-v2.py rollback")
